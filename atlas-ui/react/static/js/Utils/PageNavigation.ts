// atlas-ui/react/static/js/Utils/PageNavigation.ts — moving inside the world without
// reloading the document.
//
// 2026-10-31 (P2 of docs/frontend-redesign/16-shell-unification.md). Before this,
// every level change was `window.location.href = ...` (38 call sites): the browser
// threw away the document, re-fetched a template, re-ran a mount point, rebuilt
// every 3D scene and re-mounted the economy dock. The world has three levels and
// moving between them felt like leaving the game.
//
// How it works — PJAX-lite, no server change:
//   1. fetch the target URL (it still server-renders a complete document)
//   2. DOMParser it and pull the JSON data islands out
//   3. hand those to the router, which swaps the layout in place
//   4. pushState so the URL, back and forward still mean what they say
//
// Why not react-router: `/planet/<name>` has no client-side data source. The 3D
// payload is generated by `pymodules/` and serialised into the page. Keeping the
// server as the single source of truth is worth one extra HTTP round trip and a
// ~40KB HTML body per hop.
//
// Deliberately NOT routed through here:
//   · `POST /navigate` — a coordinate jump changes the session's galaxy, charges
//     fuel and earns its 950ms warp. It stays a real navigation.
//   · `/multiverse/exit`, `/onboarding`, `/universe-faq` — different applications.

import { viewFromDocument, syncDataIslands, syncDocumentMeta, type GameView } from "../Shell/viewData.ts";

type Listener = (view: GameView) => void;

const listeners = new Set<Listener>();
const cache = new Map<string, Document>();
const CACHE_LIMIT = 12;

let fade: HTMLDivElement | null = null;
let inFlight = 0;

export const subscribe = (listener: Listener): (() => void) => {
  listeners.add(listener);
  return () => listeners.delete(listener);
};

const emit = (view: GameView) => {
  for (const listener of listeners) listener(view);
};

const prefersReducedMotion = () => {
  try {
    return window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  } catch {
    return false;
  }
};

/** One fixed layer, created on first use; never inside the React tree. */
const getFade = (): HTMLDivElement => {
  if (fade && document.body.contains(fade)) return fade;
  fade = document.createElement("div");
  fade.className = "atlas-view-fade";
  fade.setAttribute("aria-hidden", "true");
  document.body.appendChild(fade);
  return fade;
};

const setFading = (active: boolean) => {
  if (prefersReducedMotion()) return;
  getFade().setAttribute("data-active", active ? "true" : "false");
};

const normalize = (url: string): { path: string; href: string } => {
  const target = new URL(url, window.location.origin);
  return { path: target.pathname + target.search, href: target.pathname + target.search + target.hash };
};

const fetchDocument = async (path: string): Promise<Document> => {
  const cached = cache.get(path);
  if (cached) return cached;

  const response = await fetch(path, { credentials: "same-origin", headers: { Accept: "text/html" } });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);

  const doc = new DOMParser().parseFromString(await response.text(), "text/html");
  cache.set(path, doc);
  if (cache.size > CACHE_LIMIT) {
    const oldest = cache.keys().next().value;
    if (oldest) cache.delete(oldest);
  }
  return doc;
};

/**
 * Go to `url` without a document load.
 *
 * Resolves to false when the caller must fall back to a real navigation (unknown
 * route, failed fetch, or a server redirect that produced a document without the
 * expected data islands — e.g. `/system/5` with no galaxy in the session).
 */
export async function navigate(url: string): Promise<boolean> {
  const { path, href } = normalize(url);

  if (path === window.location.pathname + window.location.search) return true;

  // Non-game routes are other documents; let the browser have them.
  if (!/^\/(galaxy|system|planet)(\/|$)/.test(path)) return false;

  inFlight += 1;
  setFading(true);

  try {
    const [doc] = await Promise.all([
      fetchDocument(path),
      prefersReducedMotion() ? Promise.resolve() : new Promise((resolve) => setTimeout(resolve, 150)),
    ]);

    const view = viewFromDocument(doc, path);
    if (!view) return false;

    syncDataIslands(doc);
    syncDocumentMeta(doc, path);
    window.history.pushState({ atlas: true }, "", href);
    emit(view);
    return true;
  } catch {
    return false;
  } finally {
    inFlight -= 1;
    if (inFlight === 0) {
      // One frame after the swap so the new scene has committed before the veil
      // lifts; otherwise the fade lifts on an empty stage.
      requestAnimationFrame(() => requestAnimationFrame(() => setFading(false)));
    }
  }
}

/**
 * The only call sites should need: in-world if possible, real navigation if not.
 * Every failure mode above (no data islands, 302 to `/` because the session has
 * no galaxy, a route this build does not know) ends as a normal page load, so
 * the worst case is exactly what the code did before P2.
 */
export async function go(url: string): Promise<void> {
  if (!(await navigate(url))) window.location.href = url;
}

/** Drop a cached view so a revisit reflects the new visit state. */
export const invalidate = (url: string) => {
  cache.delete(normalize(url).path);
};

/** Wire back/forward. Returns an unsubscribe for the owner to call on unmount. */
export const startHistorySync = (): (() => void) => {
  const onPop = async () => {
    const path = window.location.pathname + window.location.search;
    if (!/^\/(galaxy|system|planet)(\/|$)/.test(path)) return;

    setFading(true);
    try {
      const doc = await fetchDocument(path);
      const view = viewFromDocument(doc, path);
      if (!view) {
        window.location.reload();
        return;
      }
      syncDataIslands(doc);
      syncDocumentMeta(doc, path);
      emit(view);
    } catch {
      window.location.reload();
    } finally {
      requestAnimationFrame(() => requestAnimationFrame(() => setFading(false)));
    }
  };

  window.addEventListener("popstate", onPop);
  return () => window.removeEventListener("popstate", onPop);
};
