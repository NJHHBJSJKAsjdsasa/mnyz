def cmd_planet_cache_version(args: argparse.Namespace) -> int:
    from uuid import UUID

    from .infra.db import Database
    from .repo.planet_cache import bump, cache_universe_id

    try:
        universe_id = str(UUID(args.universe_id))
    except ValueError:
        print("--universe-id 必须是 uuid", file=sys.stderr)
        return 2
    settings = Settings.from_env()
    if settings.problems:
        print("配置问题: " + "; ".join(settings.problems), file=sys.stderr)
        return 2
    db = Database(settings.database_url)
    db.open()
    try:
        with db.transaction() as conn:
            cache_id = cache_universe_id(universe_id)
            version = bump(conn, cache_id)
    finally:
        db.close()
    print(
        json.dumps(
            {"universe_id": universe_id, "cache_universe_id": cache_id, "generator_version": version},
            indent=2,
        )
    )
    return 0


def cmd_universe_align(args: argparse.Namespace) -> int:
    """Align universes.seed with the local atlas.ini seed (full sha256)."""

    import configparser
    import hashlib

    from .infra.db import Database

    parser = configparser.ConfigParser()
    path = Path(args.atlas_ini)
    if not path.exists():
        print(f"找不到 {path}", file=sys.stderr)
        return 2
    parser.read(path)
    seed_str = parser.get("Settings", "seed", fallback="").strip()
    origin = parser.get("Settings", "cosmic_origin_time", fallback="0").strip()
    if not seed_str:
        print("atlas.ini 缺少 seed", file=sys.stderr)
        return 2
    seed = int(hashlib.sha256(seed_str.encode("utf-8")).hexdigest(), 16)

    settings = Settings.from_env()
    if settings.problems:
        print("配置问题: " + "; ".join(settings.problems), file=sys.stderr)
        return 2
    db = Database(settings.database_url)
    db.open()
    try:
        with db.transaction() as conn:
            row = conn.execute(
                """
                UPDATE universes SET seed = %s, cosmic_origin_time = %s
                 WHERE seed_name = %s
                RETURNING id, seed_name, seed, cosmic_origin_time
                """,
                (seed, int(origin or 0), args.seed_name),
            ).fetchone()
    finally:
        db.close()
    if row is None:
        print(f"宇宙 {args.seed_name} 不存在", file=sys.stderr)
        return 2
    print(
        json.dumps(
            {
                "id": str(row["id"]),
                "seed_name": row["seed_name"],
                "seed": int(row["seed"]),
                "cosmic_origin_time": int(row["cosmic_origin_time"]),
            },
            indent=2,
        )
    )
    return 0


def cmd_flag_set(args: argparse.Namespace) -> int:
    from .infra.db import Database
    from .repo import cutover as cutover_repo

    settings = Settings.from_env()
    if settings.problems:
        print("配置问题: " + "; ".join(settings.problems), file=sys.stderr)
        return 2
    if args.mode not in {"local", "shadow", "server"}:
        print("--mode 必须是 local/shadow/server", file=sys.stderr)
        return 2
    db = Database(settings.database_url)
    db.open()
    try:
        with db.transaction() as conn:
            cutover_repo.set_flag(conn, args.flag, args.mode, args.pct, "cli")
            row = conn.execute(
                "SELECT name, mode, rollout_pct FROM feature_flags WHERE name = %s", (args.flag,)
            ).fetchone()
    finally:
        db.close()
    print(json.dumps(dict(row), indent=2, ensure_ascii=False) if row else "{}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="python -m server.cli", description="Atlas server CLI")
    sub = parser.add_subparsers(dest="command", required=True)

    init = sub.add_parser("init-dev", help="生成开发用密钥与 .env.server")
    init.add_argument("--dsn")
    init.add_argument("--force", action="store_true")
    init.set_defaults(func=cmd_init_dev)

    create = sub.add_parser("create-db", help="创建数据库与角色")
    create.add_argument("--dsn")
    create.set_defaults(func=cmd_create_db)

    migrate = sub.add_parser("migrate", help="执行 alembic 迁移")
    migrate.add_argument("revision", nargs="?", default="head")
    migrate.set_defaults(func=cmd_migrate)

    check = sub.add_parser("check", help="启动自检")
    check.set_defaults(func=cmd_check)

    status = sub.add_parser("status", help="打印运行状态")
    status.set_defaults(func=cmd_status)

    backfill = sub.add_parser("cache-backfill", help="SQLite/JSON 缓存回填 PostgreSQL")
    backfill.add_argument("--sqlite", default="internal_data/cache/atlas_cache.db")
    backfill.add_argument("--json-dir", default="internal_data/cache")
    backfill.add_argument("--universe-id")
    backfill.add_argument("--sample", type=float, default=0.01, help="抽样比对比例")
    backfill.set_defaults(func=cmd_cache_backfill)

    cache_inspect = sub.add_parser("cache-inspect", help="查看 PG 缓存命中规模与版本")
    cache_inspect.add_argument("--universe-id")
    cache_inspect.set_defaults(func=cmd_cache_inspect)

    cache_version = sub.add_parser("cache-version", help="提升生成器版本使旧行失效")
    cache_version.add_argument("--universe-id")
    cache_version.set_defaults(func=cmd_cache_version)

    planet_version = sub.add_parser("planet-cache-version", help="提升服务端行星缓存版本")
    planet_version.add_argument("--universe-id", required=True, help="universes.id")
    planet_version.set_defaults(func=cmd_planet_cache_version)

    flag_set = sub.add_parser("flag-set", help="设置灰度开关（domain.explore 等）")
    flag_set.add_argument("flag")
    flag_set.add_argument("--mode", default="local")
    flag_set.add_argument("--pct", type=int, default=0)
    flag_set.set_defaults(func=cmd_flag_set)

    align = sub.add_parser("universe-align", help="用 atlas.ini 的 seed 对齐服务端宇宙")
    align.add_argument("--atlas-ini", default="atlas.ini")
    align.add_argument("--seed-name", default="atlas-main")
    align.set_defaults(func=cmd_universe_align)
    return parser


def main(argv: list[str] | None = None) -> int:
    load_env_file()
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
